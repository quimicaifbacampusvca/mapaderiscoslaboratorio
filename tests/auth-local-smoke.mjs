import fs from 'node:fs';
import assert from 'node:assert/strict';
import vm from 'node:vm';
const store = new Map();
const requests = [];
const ctx = { console, localStorage: {getItem: k => store.get(k) || null, setItem:(k,v)=>store.set(k,String(v)), removeItem:k=>store.delete(k)}, location:{origin:'https://example.org',pathname:'/index.html'}, RoomBackend:{ request: async (path,options) => {
  requests.push({path,options});
  if(path==='/api/auth/me') return {usuario:{id:'p1',nome:'Professor',papel:'professor'}};
  if(path==='/api/auth/logout') return {ok:true};
  return {usuario:{id:'p1',nome:'Professor',papel:'professor'},sessionToken:'token123'};
}}};
ctx.window=ctx;
vm.runInNewContext(fs.readFileSync(new URL('../js/auth.js',import.meta.url),'utf8'),ctx);
const user=await ctx.AuthAPI.registerUser('Professor','TESTE@EXAMPLE.ORG','senha123','professor');
assert.equal(user.id,'p1');
assert.equal(JSON.parse(requests[0].options.body).email,'teste@example.org');
assert.equal(ctx.AuthAPI.isAuthenticated(),true);
await ctx.AuthAPI.validateSession();
assert.equal(requests[1].path,'/api/auth/me');
await ctx.AuthAPI.logoutUser();
assert.equal(ctx.AuthAPI.isAuthenticated(),false);
console.log('Remote auth contract smoke: OK');
