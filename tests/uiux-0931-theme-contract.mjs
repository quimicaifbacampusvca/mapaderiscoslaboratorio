import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const R=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>readFileSync(resolve(R,p),'utf8');
const html=read('index.html'),a11y=read('css/acessibilidade.css'),theme=read('css/temas-contraste.css');
const sw=read('sw.js');
assert.match(html,/<link rel="stylesheet" href="css\/temas-contraste\.css">/);
assert.ok(html.indexOf('href="css/temas-contraste.css"')>html.indexOf('href="css/acessibilidade.css"'));
assert.match(sw,/css\/temas-contraste\.css/);
assert.match(sw,/uiux-0\.9\.3\.2-visibility-v1/);
for(const v of ['dark','light'])assert.ok(theme.includes('html[data-mrl-theme="'+v+'"]'));
for(const v of ['dark','light'])assert.ok(theme.includes('[data-mrl-theme="'+v+'"]'));
for(const s of ['--mrl-ui-card','--mrl-ui-ink','--mrl-ui-muted','--mrl-ui-control','--mrl-ui-focus'])assert.ok(theme.includes(s));
for(const s of ['.home-recent','.library-home-launch','.home-card','.tree-item','.right-panel','.left-panel','.room-card','.settings-panel','.library-panel'])assert.ok(theme.includes(s),s);
assert.doesNotMatch(theme,/[{}]\s*\*\s*\{/);
assert.doesNotMatch(theme,/\b(drawImage|requestDraw)\s*\(/);
assert.ok(a11y.includes('data-mrl-cvd'));
assert.doesNotMatch(a11y,/html\[data-mrl-theme="light"\] :is\(\.left-panel,\.right-panel,\.settings-panel,header\.topbar,\.home-screen,\.library-panel\) :is\(h1,h2,h3,p,label,span,strong,small,legend\)/);
assert.match(read('js/accessibility.js'),/mrl_accessibility_preferences_v1/);
console.log('UIUX-0.9.3.1 — temas, contraste, PWA, preservação científica: OK');
